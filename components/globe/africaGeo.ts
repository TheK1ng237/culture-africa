export const AFRICA_POLYGONS: LngLat[][] = [AFRICA_MAINLAND, MADAGASCAR];

export function pointInPolygon(lng: number, lat: number, polygon: LngLat[]): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    const intersects = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

export function isLand(lng: number, lat: number): boolean {
  return AFRICA_POLYGONS.some((polygon) => pointInPolygon(lng, lat, polygon));
}
